#[test]
fn sequential_measures_retain_prior_tie_order() {
    let mut order = (0..20).collect();
    super::descending(
        &mut order,
        &[
            3.0, 0.0, 3.0, 2.0, 1.0, 0.0, 2.0, 3.0, 1.0, 0.0, 2.0, 3.0, 0.0, 1.0, 3.0, 2.0, 0.0,
            1.0, 2.0, 3.0,
        ],
    );
    assert_eq!(
        order,
        vec![0, 7, 14, 11, 19, 2, 6, 3, 15, 18, 10, 4, 8, 13, 17, 5, 9, 1, 12, 16]
    );
    super::descending(
        &mut order,
        &[
            0.0, 3.0, 2.0, 1.0, 0.0, 3.0, 2.0, 1.0, 0.0, 3.0, 2.0, 1.0, 0.0, 3.0, 2.0, 1.0, 0.0,
            3.0, 2.0, 1.0,
        ],
    );
    assert_eq!(
        order,
        vec![9, 1, 13, 17, 5, 10, 14, 2, 6, 18, 11, 19, 3, 15, 7, 12, 0, 8, 4, 16]
    );
    super::descending(
        &mut order,
        &[
            3.0, 3.0, 5.0, 3.0, 1.0, 3.0, 4.0, 4.0, 1.0, 3.0, 4.0, 4.0, 0.0, 4.0, 5.0, 3.0, 0.0,
            4.0, 4.0, 4.0,
        ],
    );
    assert_eq!(
        order,
        vec![14, 2, 11, 13, 17, 10, 6, 18, 7, 19, 15, 0, 9, 3, 1, 5, 8, 4, 12, 16]
    );
}
